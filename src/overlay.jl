# The overlay (a copy of the package's Project.toml plus shims that load its original
# files) and the per-run environment that points the package at it.

const CHECKUP = Base.PkgId(Base.UUID("ca055ede-32eb-4961-937e-82d9c5ec6430"), "DispatchCheckup")

_project_file(dir) = (files = filter(isfile, joinpath.(dir, Base.project_names));
                      isempty(files) ? nothing : first(files))

# Where the active environment loads `name` from: its id and UUID, package root, entry file,
# project file, and its extensions' entry files (found in the same order as Base finds them)
# and trigger packages.
function _locate(name::Symbol)
    id = Base.identify_package(String(name))
    id === nothing && error("DispatchCheckup: package $name is not in the active environment")
    uuid = id.uuid
    uuid === nothing && error("DispatchCheckup: package $name has no UUID " *
                              "(is it a package without a Project.toml?)")
    entry = Base.locate_package(id)
    entry === nothing && error("DispatchCheckup: cannot find the source of $name " *
                               "(does the environment need `Pkg.instantiate()`?)")
    root = dirname(entry)
    while (file = _project_file(root)) === nothing ||
          get(TOML.parsefile(file), "uuid", "") != string(uuid)
        dirname(root) == root && error("DispatchCheckup: no Project.toml of $name above $entry")
        root = dirname(root)
    end
    project = TOML.parsefile(file)
    uuids = merge(get(project, "deps", Dict()), get(project, "weakdeps", Dict()))
    exts, triggers = Dict{Base.PkgId,String}(), Dict{Base.PkgId,Vector{Base.PkgId}}()
    for (ext, packages) in get(project, "extensions", Dict())
        pkg = Base.PkgId(Base.uuid5(uuid, ext), ext)
        exts[pkg] = Base.find_ext_path(normpath(dirname(entry), ".."), ext)
        triggers[pkg] = [Base.PkgId(Base.UUID(uuids[n]), n) for n in
                         (packages isa String ? (packages,) : packages)]
    end
    return (; id, uuid, root, entry, file, project, exts, triggers)
end

# Each shim requires DispatchCheckup and loads the original file through it. The
# configuration is a literal, so that changing it invalidates the precompiled image.
function _shim(pkg::Base.PkgId, entry::String, cfg::Config)
    unstable = [(e.name, e.location) for e in cfg.unstable]
    args = join((_literal(pkg), _literal(cfg.id), repr.((entry, cfg.root, unstable, cfg.mode,
                                                        cfg.union_limit))...), ",\n        ")
    return """
        # Generated by DispatchCheckup: loads the original $(basename(entry)) with
        # DispatchDoctor's checks. Commenting out `dispatch_doctor` leaves this file unused.
        let checkup = Base.require($(_literal(CHECKUP)))
            load = Base.invokelatest(Base.getglobal, checkup, :_load_checked)
            Base.invokelatest(load, Base.@__MODULE__,
                $args)
        end
        """
end

_literal(p::Base.PkgId) = "Base.PkgId(Base.UUID(\"$(p.uuid)\"), $(repr(p.name)))"

# Write a file only when its content changes, so that precompiled images stay valid.
function _update(path::String, content::Vector{UInt8})
    isfile(path) && read(path) == content && return path
    mkpath(dirname(path))
    temporary = "$path.$(getpid()).tmp"
    write(temporary, content)
    return mv(temporary, path; force = true)
end

# The overlay lives in DispatchCheckup's scratch space `overlays` in the first depot, in one
# directory per checkout and configuration (both are in the target's shim), so that runs with
# other options never share its shims. Scratch records the space's use, by DispatchCheckup's
# project, in the depot's logs/scratch_usage.toml, and Pkg.gc keeps a scratch space only while
# a project recorded as using it exists (otherwise any Pkg.gc, such as the one that Pkg runs
# on its own after a `Pkg.update`, deletes the overlay under the runs that load from it).
function _write_overlay(t, cfg::Config)
    key = string(hash(_shim(t.id, t.entry, cfg)); base = 16)
    dir = joinpath(Scratch.get_scratch!(CHECKUP.uuid, "overlays"), "$(t.id.name)-$key")
    _update(joinpath(dir, relpath(t.file, t.root)), read(t.file))
    shims = Dict{Base.PkgId,String}()
    for (pkg, entry) in [t.id => t.entry; collect(t.exts)]
        relative = relpath(entry, t.root)
        startswith(relative, "..") && error("DispatchCheckup: $entry is outside $(t.root)")
        shims[pkg] = _update(normpath(dir, relative), Vector{UInt8}(_shim(pkg, entry, cfg)))
    end
    return dir, shims
end

_write_toml(path::String, data::AbstractDict) = open(io -> TOML.print(io, data; sorted = true), path, "w")

# The per-run environment: a copy of the active manifest in which the package comes from
# the overlay (and also depends on DispatchCheckup), and preferences that set
# DispatchDoctor's options for it.
function _write_environment(t, overlay::String, cfg::Config)
    dir = mktempdir(; prefix = "dispatchcheckup-")
    project = Base.active_project()
    file = project === nothing ? nothing : Base.project_file_manifest_path(project)
    manifest = file === nothing ? Dict{String,Any}() : TOML.parsefile(file)
    haskey(manifest, "manifest_format") || (manifest = Dict("manifest_format" => "2.0", "deps" => manifest))
    deps = get!(Dict{String,Any}, manifest, "deps")
    if file !== nothing  # (otherwise `deps` is empty)
        for records in values(deps), record in records
            haskey(record, "path") && (record["path"] = normpath(dirname(file), record["path"]))
        end
    end
    records = get!(Vector{Any}, deps, t.id.name)::Vector{Any}  # (a TOML array of tables)
    index = findfirst(r -> get(r, "uuid", "") == string(t.id.uuid), records)
    record = index === nothing ? push!(records, _record(t))[end] : records[index]
    for key in ("git-tree-sha1", "repo-url", "repo-rev", "repo-subdir", "pinned")
        delete!(record, key)
    end
    record["path"] = overlay
    own = get(record, "deps", Dict{String,Any}())
    own isa AbstractVector && (own = Dict(n => only(deps[n])["uuid"] for n in own))
    record["deps"] = merge(own, Dict(CHECKUP.name => string(CHECKUP.uuid)))
    _write_toml(joinpath(dir, "Project.toml"), Dict("extras" => Dict(t.id.name => string(t.id.uuid))))
    _write_toml(joinpath(dir, "Manifest.toml"), manifest)
    _write_toml(joinpath(dir, "LocalPreferences.toml"), Dict(t.id.name => Dict(
        "dispatch_doctor_mode" => cfg.mode, "dispatch_doctor_union_limit" => cfg.union_limit,
        "dispatch_doctor_codegen_level" => "debug")))
    return dir
end

# A manifest record for a package that the active manifest does not list (for example
# the active project itself).
function _record(t)
    record = Dict{String,Any}("uuid" => string(t.id.uuid))
    for key in ("version", "deps", "weakdeps", "extensions", "entryfile")
        haskey(t.project, key) && (record[key] = t.project[key])
    end
    return record
end
